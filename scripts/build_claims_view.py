#!/usr/bin/env python3
"""Generate kb/_views/claims.md: one compact entry per claim.

Reads kb/roles/*.md ('### A-...' blocks) and writes id, canonical, tier and
metrics for every claim, plus each role's header facts. Variants, sources and
notes are left out; open the role file for those.

Usage:
    python scripts/build_claims_view.py            # write the view
    python scripts/build_claims_view.py --check    # exit 1 if the view is stale
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES = ROOT / "kb" / "roles"
OUT = ROOT / "kb" / "_views" / "claims.md"

FM_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)
HEAD_RE = re.compile(r"^### (A-\S+)\s*$", re.M)
FIELD_RE = re.compile(r"^(canonical|tier|metrics):\s*(.*)$", re.M)


def frontmatter(text):
    m = FM_RE.match(text)
    fm = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            fm[k.strip()] = v.strip()
    return fm


def claims(text):
    heads = list(HEAD_RE.finditer(text))
    for i, h in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        block = text[h.end():end]
        fields = {k: v.strip() for k, v in FIELD_RE.findall(block)}
        yield h.group(1), fields


def build():
    lines = [
        "# Claims view (generated, do not edit)",
        "",
        "Generated by scripts/build_claims_view.py from kb/roles/*.md. One entry per claim:",
        "`id | tier | canonical | metrics`. Variants, sources and notes live in the role file.",
        "Numbers may be used only as listed in metrics, copied exactly.",
        "",
    ]
    total = 0
    for path in sorted(ROLES.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        fm = frontmatter(text)
        lines += [
            f"## {fm.get('id', path.stem)}",
            f"employer: {fm.get('employer', '')}",
            f"title: {fm.get('title', '')}",
            f"dates: {fm.get('start', '')} to {fm.get('end', '')}",
            f"location: {fm.get('location', '')}",
            f"file: kb/roles/{path.name}",
            "",
        ]
        for cid, f in claims(text):
            total += 1
            lines.append(f"### {cid} | {f.get('tier', '')}")
            lines.append(f"canonical: {f.get('canonical', '')}")
            lines.append(f"metrics: {f.get('metrics', '')}")
            lines.append("")
    lines.insert(5, f"Total claims: {total}")
    return "\n".join(lines).rstrip() + "\n", total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    content, total = build()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print("kb/_views/claims.md is stale; run scripts/build_claims_view.py")
            return 1
        print(f"claims view current ({total} claims)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {total} claims, {len(content)} chars (~{len(content)//4} tokens)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
